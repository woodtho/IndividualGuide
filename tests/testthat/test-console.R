console_wait <- function(state, timeout = 45) {
  deadline <- Sys.time() + timeout
  while (!is.null(state$pending) && Sys.time() < deadline) later::run_now(0.05)
  expect_null(state$pending, info = state$text)
  invisible(state)
}

test_that("real console keeps variables, captures conditions and renders plots", {
  session <- shiny::MockShinySession$new(); on.exit(session$close())
  store <- new_test_store(list(raw = data.frame(x = 1:3)))
  state <- ig_console_state(store, session)
  expect_null(state$process)
  expect_true(ig_console_submit(state, store, "answer <- sum(raw$x); answer\nmessage('hello')\nwarning('careful')\nplot(1:3)"))
  console_wait(state)
  expect_match(state$text, "\\[1\\] 6")
  expect_match(state$text, "hello")
  expect_match(state$text, "Warning: careful")
  expect_identical(state$status, "Ready")
  expect_length(state$plots, 1)
  expect_true(file.exists(state$plots))
  pid <- state$process$get_pid()
  ig_console_submit(state, store, "answer + 4\ncat('stderr-value', file=stderr())\nraw$x <- 0\nstop('test error')")
  console_wait(state)
  expect_match(state$text, "\\[1\\] 10")
  expect_match(state$text, "Error: test error")
  expect_match(state$text, "stderr-value")
  expect_identical(state$status, "Error")
  expect_equal(isolate(store$tables$raw$x), 1:3)
  ig_console_submit(state, store, "answer + 1")
  console_wait(state)
  expect_match(state$text, "\\[1\\] 7")
  expect_identical(state$process$get_pid(), pid)
  expect_length(state$plots, 1L) # Calculations must not add blank PNG pages.
  ig_console_submit(state, store, "library(ggplot2); ggplot(raw, aes(x)) + geom_histogram(bins=3)")
  console_wait(state)
  expect_identical(state$status, "Ready")
  expect_length(state$plots, 2L)
  ig_console_submit(state, store, "nrow(raw) + answer", refresh = TRUE)
  console_wait(state)
  expect_match(state$text, "\\[1\\] 9")
  expect_identical(state$status, "Ready")
  process <- state$process
  ig_console_reset(state)
  process$wait(5000)
  expect_false(process$is_alive()); expect_null(state$process)
  expect_length(state$plots, 0)
})

test_that("console handles invalid code, output limits and a crashed worker", {
  session <- shiny::MockShinySession$new(); on.exit(session$close())
  store <- make_store(); state <- ig_console_state(store, session)
  ig_console_submit(state, store, "if ("); console_wait(state)
  expect_match(state$text, "Error:")
  ig_console_submit(state, store, "cat(strrep('x', 500000)); cat('ENDMARKER')")
  console_wait(state)
  expect_lt(nchar(state$text), 300001)
  expect_match(state$text, "ENDMARKER")
  ig_console_submit(state, store, "q('no')"); console_wait(state)
  expect_match(state$text, "process ended")
  ig_console_submit(state, store, "'RESTARTED'"); console_wait(state)
  expect_match(state$text, "RESTARTED")
  expect_identical(state$status, "Ready")
  directory <- state$directory; process <- state$process
  session$close(); process$wait(5000)
  expect_false(process$is_alive()); expect_false(dir.exists(directory))
})

test_that("console module interrupts workers and project replacement retires work", {
  withr::local_options(ig.recovery_dir = tempfile(), ig.catalogue_dir = tempfile())
  shiny::testServer(app_server, {
    root <- session$rootScope()
    state <- r_console$state
    session$setInputs(`r_console-request` = list(code = "Sys.sleep(60); late <- TRUE"))
    root$flushReact()
    expect_false(is.null(state$pending))
    process <- state$process
    session$setInputs(`r_console-stop` = 1); root$flushReact()
    process$wait(5000)
    expect_false(process$is_alive()); expect_null(state$pending)
    expect_identical(state$status, "Stopped")
    expect_equal(state$history_generation, 0L)
    ig_console_submit(state, store, "console_only <- 123"); console_wait(state)
    process <- state$process
    path <- tempfile(fileext = ".igpx")
    project_save(store, path)
    corrupt <- tempfile(fileext = ".igpx"); writeLines("invalid", corrupt)
    expect_false(load_from_local_path(corrupt)); root$flushReact()
    expect_identical(state$process, process); expect_true(process$is_alive())
    expect_true(load_from_local_path(path)); root$flushReact()
    process$wait(5000)
    expect_false(process$is_alive()); expect_null(state$process)
    expect_gt(state$history_generation, 0L)
    expect_true("console" %in% tabs_rv$open)
    ig_console_submit(state, store, "Sys.sleep(60); late <- TRUE")
    process <- state$process
    recovery_pending(FALSE)
    expect_true(reset_project()); root$flushReact()
    process$wait(5000)
    expect_false(process$is_alive()); expect_null(state$process)
    expect_true("console" %in% tabs_rv$open)
  })
})

test_that("console sessions stay separate and refresh retires old imports", {
  first <- shiny::MockShinySession$new(); second <- shiny::MockShinySession$new()
  on.exit({first$close(); second$close()})
  store <- new_test_store(list(`raw data` = data.frame(x = 1:3)))
  a <- ig_console_state(store, first); b <- ig_console_state(store, second)
  ig_console_submit(a, store, "private <- 9; sum(`raw data`$x)")
  ig_console_submit(b, store, "cat('PRIVATE=', exists('private'), sep='')")
  console_wait(a); console_wait(b)
  expect_match(a$text, "\\[1\\] 6"); expect_match(b$text, "PRIVATE=FALSE")
  expect_false(identical(a$process$get_pid(), b$process$get_pid()))
  store$tables <- list(new_data = data.frame(x = 7))
  ig_console_submit(a, store, "cat('OLD=', exists('raw data'), ' NEW=', new_data$x, ' PRIVATE=', private, sep='')", refresh = TRUE)
  console_wait(a)
  expect_match(a$text, "OLD=FALSE NEW=7 PRIVATE=9")
})
