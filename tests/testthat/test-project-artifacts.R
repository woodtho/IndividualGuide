test_that("rendered reports and companions survive removal of the original session files", {
  store <- new_test_store(list(raw = data.frame(x = 1:3)))
  p <- default_report_params("report_result")
  p$title <- "Saved report"; p$items <- list(list(name = "raw", heading = "Data"))
  result <- execute_report(p, shiny::isolate(store$tables))
  expect_null(result$error)
  task <- task_def("report1", "report", inputs = "raw", output = "report_result", params = p)
  task$outputs <- list(list(name = "report_result", kind = "report", path = result$report_path))
  task$status <- "success"; task$run_time <- Sys.time()
  shiny::isolate(store_set_task(store, task))
  path <- tempfile(fileext = ".igpx")
  project_save(store, path)
  expect_true(any(startsWith(utils::unzip(path, list = TRUE)$Name, "reports/")))
  original_directory <- dirname(result$report_path)
  stopifnot(startsWith(normalizePath(original_directory, winslash = "/"), normalizePath(tempdir(), winslash = "/")))
  unlink(original_directory, recursive = TRUE)
  loaded <- make_store()
  on.exit(project_release_assets(loaded), add = TRUE)
  expect_true(project_load(loaded, path)$ok)
  restored_path <- shiny::isolate(loaded$tasks$report1$outputs[[1]]$path)
  expect_true(file.exists(restored_path))
  expect_identical(shiny::isolate(loaded$tasks$report1$status), "success")
  expect_true(all(file.exists(file.path(dirname(restored_path), c("report.Rmd", "data.rds")))))
  expect_equal(readRDS(file.path(dirname(restored_path), "data.rds"))$raw, data.frame(x = 1:3))
  expect_match(paste(readLines(restored_path, warn = FALSE), collapse = "\n"), "Saved report", fixed = TRUE)
  second <- tempfile(fileext = ".igpx")
  project_save(loaded, second)
  expect_true(project_load(loaded, second)$ok)
  expect_false(file.exists(restored_path))
  expect_true(file.exists(shiny::isolate(loaded$tasks$report1$outputs[[1]]$path)))
})

test_that("missing lazy imports mark descendants stale without discarding saved snapshots", {
  skip_if_not_installed("RSQLite")
  store <- new_test_store()
  db <- tempfile(fileext = ".sqlite")
  con <- DBI::dbConnect(RSQLite::SQLite(), db)
  DBI::dbWriteTable(con, "data", data.frame(x = 1:4)); DBI::dbDisconnect(con)
  p <- default_import_params("raw")
  p$source_kind <- "db"; p$db_conn_mode <- "form"; p$db_driver <- "sqlite"
  p$db_database <- db; p$db_table <- "data"; p$db_collect <- FALSE
  add_test_task(store, "imp", "import_data", params = p)
  h <- default_first_last_params("rows"); h$input_table <- "raw"; h$n <- 2
  add_test_task(store, "head", "first_last_n", inputs = "raw", params = h)
  expect_true(shiny::isolate(run_task_from_store(store, "imp")))
  expect_true(shiny::isolate(run_task_from_store(store, "head")))
  path <- tempfile(fileext = ".igpx"); project_save(store, path)
  shiny::isolate(store_close_connections(store))
  loaded <- make_store(); project_load(loaded, path)
  expect_identical(shiny::isolate(loaded$tasks$imp$status), "pending")
  expect_true(shiny::isolate(loaded$tasks$imp$invalidated))
  expect_identical(shiny::isolate(loaded$tasks$head$status), "pending")
  expect_true(shiny::isolate(loaded$tasks$head$invalidated))
  expect_equal(shiny::isolate(loaded$tables$rows), data.frame(x = 1:2))
  expect_false("raw" %in% names(shiny::isolate(loaded$tables)))
  expect_match(shiny::isolate(loaded$tasks$imp$restoration_note), "Reconnect")
})

test_that("modern plots, widgets and fitted models remain usable after a project round trip", {
  store <- new_test_store(list(raw = mtcars))
  plot <- ggplot2::ggplot(mtcars, ggplot2::aes(wt, mpg)) + ggplot2::geom_point()
  shiny::isolate({
    store_add_object(store, "image", plot, list(kind = "image"))
    store_add_object(store, "interactive", ggiraph::girafe(ggobj = plot), list(kind = "plot"))
    store_add_object(store, "fit", stats::lm(mpg ~ wt, mtcars), list(kind = "model"))
  })
  path <- tempfile(fileext = ".igpx")
  expect_no_error(project_save(store, path))
  loaded <- make_store()
  expect_true(project_load(loaded, path)$ok)
  objects <- shiny::isolate(loaded$objects)
  expect_equal(ggplot2::ggplot_build(objects$image$value)$data, ggplot2::ggplot_build(plot)$data)
  expect_s3_class(objects$interactive$value, "girafe")
  expect_equal(stats::predict(objects$fit$value, mtcars[1:3, ]), stats::predict(stats::lm(mpg ~ wt, mtcars), mtcars[1:3, ]))
})

test_that("missing native companions and unsafe report paths preserve the current project", {
  incoming <- new_test_store()
  shiny::isolate(store_add_object(incoming, "fit", stats::lm(mpg ~ wt, mtcars), list(kind = "model")))
  path <- tempfile(fileext = ".igpx"); project_save(incoming, path)
  root <- project_unzip(path)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  descriptor <- project_read_json(list.files(file.path(root, "objects"), pattern = "\\.json$", full.names = TRUE)[[1L]])
  expect_identical(descriptor$encoding, "r-native-rds")
  unlink(file.path(root, "objects", descriptor$file))
  project_zip_dir(root, path)
  current <- new_test_store(list(keep = data.frame(x = 42)))
  before <- shiny::isolate(shiny::reactiveValuesToList(current))
  expect_error(project_load(current, path), "Missing native payload")
  expect_identical(shiny::isolate(shiny::reactiveValuesToList(current)), before)
  for (artifact in c("../../outside.html", "reports/flow/task/missing.html")) {
    bad <- new_test_store()
    task <- task_def("report", "report", output = "rendered", params = default_report_params("rendered"))
    task$outputs <- list(list(name = "rendered", kind = "report", artifact_path = artifact))
    shiny::isolate(store_set_task(bad, task))
    project_save(bad, path)
    expect_error(project_load(current, path), "artifact")
    expect_identical(shiny::isolate(shiny::reactiveValuesToList(current)), before)
  }
})

test_that("legacy JSON model formula environments remain usable for prediction", {
  model <- stats::lm(mpg ~ wt, mtcars)
  path <- tempfile(fileext = ".json")
  writeLines(jsonlite::serializeJSON(list(name = "fit", encoding = "jsonlite-r-object-json",
    value = model, meta = list(kind = "model")), digits = NA), path, useBytes = TRUE)
  result <- project_read_payload(path)
  expect_equal(stats::predict(result$value, mtcars[1:3, ]), stats::predict(model, mtcars[1:3, ]))
})
