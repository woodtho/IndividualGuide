# Keep the main file short while retaining a self-contained single-file export.
code_pipeline_files <- function(script) {
  lines <- strsplit(script, "\n", fixed = TRUE)[[1L]]
  start <- which(lines == "# Pipeline ----")[[1L]]
  loader <- c("# Generated by Individual Guide",
    "# Keep pipeline_support.R beside this file. Run this script from top to bottom.",
    "source(local({",
    "  paths <- vapply(sys.frames(), function(frame) {",
    "    path <- frame$ofile",
    "    if (is.character(path) && length(path) == 1L) path else ''",
    "  }, character(1))",
    "  paths <- paths[nzchar(paths)]",
    "  if (!length(paths)) {",
    "    argument <- grep('^--file=', commandArgs(), value = TRUE)",
    "    if (length(argument)) paths <- substring(argument, 8L)",
    "  }",
    "  directory <- if (length(paths)) dirname(normalizePath(tail(paths, 1L), mustWork = TRUE)) else getwd()",
    "  file.path(directory, 'pipeline_support.R')",
    "}), local = TRUE)", "")
  list(pipeline = paste(c(loader, lines[seq.int(start, length(lines))]), collapse = "\n"),
    support = paste(lines[seq_len(start - 1L)], collapse = "\n"), complete = script)
}

ig_write_code_bundle <- function(script, file) {
  parts <- code_pipeline_files(script)
  directory <- tempfile("ig_code_bundle_", tmpdir = tempdir())
  dir.create(directory)
  owned <- normalizePath(directory, winslash = "/", mustWork = TRUE)
  parent <- paste0(normalizePath(tempdir(), winslash = "/", mustWork = TRUE), "/")
  if (!startsWith(owned, parent) || !startsWith(basename(owned), "ig_code_bundle_")) stop("Invalid code staging directory.")
  on.exit(unlink(owned, recursive = TRUE), add = TRUE)
  writeLines(parts$pipeline, file.path(directory, "pipeline.R"), useBytes = TRUE)
  writeLines(parts$support, file.path(directory, "pipeline_support.R"), useBytes = TRUE)
  writeLines(c("Individual Guide - reproducible R pipeline", "",
    "Keep pipeline.R and pipeline_support.R in the same folder.",
    "Run Rscript --vanilla pipeline.R, or source('pipeline.R') in R.",
    "No IndividualGuide installation is required. Install the referenced R packages first.",
    "Input files and database connections still need to be available at the configured paths.",
    "The pipeline preserves your task settings, random-task seeds, logging and control flow.",
    "An optional project seed applies separately to each task, including Script steps and loop bodies.",
    "User-written Script steps are retained and can set their own seed explicitly.",
    "pipeline_support.R contains the shared calculations, validation, task metadata and logging.",
    "Download .R in the app provides the same pipeline and support together in one file."),
    file.path(directory, "README.txt"), useBytes = TRUE)
  zip::zipr(file, c("pipeline.R", "pipeline_support.R", "README.txt"), root = directory)
  invisible(file)
}
