# code_gen.R — Assemble the full pipeline R script from task definitions
#
# Each task module is responsible for writing its own r_code string into the
# task definition it saves to the store.  This file just assembles those
# snippets into a coherent, annotated script.

# ── Full script builders ───────────────────────────────────────────────────────

#' Build the complete R pipeline script from all tasks in order
#'
#' @param store  reactiveValues store
#' @return A single character string (the full .R script)
build_full_r_script <- function(store) {
  registry <- new.env(parent = emptyenv()); registry$roots <- character(0)
  previous <- options(IndividualGuide.codegen_helpers = registry)
  on.exit(options(previous), add = TRUE)
  store_sync_parameters(store)
  tasks      <- isolate(store$tasks)
  previous_namespace <- options(IndividualGuide.codegen_namespace = code_runtime_name(tasks))
  on.exit(options(previous_namespace), add = TRUE)
  # Topologically sort so the script always runs producers before consumers,
  # even when tasks were created out of order. Falls back to insertion order
  # if the dependency graph has a problem (which is reported elsewhere).
  task_order <- tryCatch(
    suppressWarnings(store_topo_order(tasks, isolate(store$task_order))),
    error = function(e) isolate(store$task_order))

  # Always-present baseline libraries
  baseline_libs <- if (any(vapply(tasks, function(task) identical(task$type, "script"), logical(1))))
    c("dplyr", "tidyr", "readr", "readxl", "lubridate") else character(0)

  # ── Pass 1: collect code snippets and harvest all library() calls ────────────
  snippets    <- list()   # id → cleaned code string (library lines stripped)
  extra_libs  <- character(0)

  lib_pattern <- "^\\s*library\\(([^)]+)\\)\\s*$"

  for (id in task_order) {
    task <- tasks[[id]]
    if (is.null(task)) next

    code <- tryCatch({
      code <- trimws(build_task_code(task))
      parse(text = code)
      code
    }, error = function(e) {
      paste0("stop(", r_val(paste0("Task '", id, "': ", conditionMessage(e)), "character"), ")")
    })
    if (!nzchar(code)) code <- paste0("stop(", r_val(paste("Configure task", id, "before exporting code."), "character"), ")")

    lines <- strsplit(code, "\n", fixed = TRUE)[[1L]]
    is_lib <- grepl(lib_pattern, lines)
    if (identical(task$type, "script")) is_lib[] <- FALSE
    # Harvest package names
    extra_libs <- c(extra_libs,
      sub(lib_pattern, "\\1", trimws(lines[is_lib])))
    # Strip library lines from body; collapse remaining non-blank leading lines
    body_lines <- lines[!is_lib]
    # Trim leading/trailing blank lines from body
    while (length(body_lines) && !nzchar(trimws(body_lines[1L])))
      body_lines <- body_lines[-1L]
    while (length(body_lines) && !nzchar(trimws(body_lines[length(body_lines)])))
      body_lines <- body_lines[-length(body_lines)]

    if (length(body_lines)) snippets[[id]] <- list(task = task, body = body_lines)
  }

  # ── Deduplicated library block ───────────────────────────────────────────────
  all_libs   <- unique(c(baseline_libs, trimws(extra_libs)))
  lib_lines  <- paste0("library(", all_libs, ")")
  reproducibility <- c(
    paste0("RNGkind(", paste(vapply(as.list(RNGkind()), code_literal, character(1)), collapse = ", "), ")"),
    paste0("options(", ig_options_code(ig_options_merge(options()[c("contrasts", "na.action")], ig_options_r_values(store))), ")"))

  header <- c(
    "# Generated by Individual Guide",
    "# Run from top to bottom. Shared support is defined once before the pipeline.",
    paste0("# R ", getRversion(), "; random tasks use their configured seeds."),
    "",
    reproducibility,
    lib_lines,
    ""
  )

  # ── Pass 2: assemble annotated task bodies ───────────────────────────────────
  task_lines <- build_control_flow_code(tasks, task_order, snippets,
    stop_on_error = isolate(store$settings)$stop_on_error,
    project_seed = isolate(store$settings)$run_seed)

  paste(c(header, task_lines), collapse = "\n")
}

# ── Code panel Shiny module ───────────────────────────────────────────────────

#' UI for the code generation panel (placed in a collapsible card)
#' @param id Identifier of the module, task, flow, or catalogue entry being addressed.
code_panel_ui <- function(id) {
  ns <- NS(id)
  bslib::card(
    bslib::card_header(
      class = "d-flex align-items-center gap-2",
      bslib::tooltip(
        shiny::actionButton(ns("copy_r"), "Copy R",
          class = "btn btn-sm btn-outline-secondary",
          icon  = shiny::icon("copy")),
        "Copy R script to clipboard"
      ),
      shiny::downloadButton(ns("dl_r"), "Download .R",
        class = "btn btn-sm btn-outline-secondary"),
      shiny::downloadButton(ns("dl_bundle"), "Download bundle",
        class = "btn btn-sm btn-primary")
    ),
    radioButtons(ns("view"), "Code view", c("Pipeline" = "pipeline", "Supporting functions" = "support", "Complete script" = "complete"),
      selected = "pipeline", inline = TRUE),
    p(class = "small text-muted", "Pipeline view uses pipeline_support.R from Download bundle. Download .R includes everything in one file. Both run without the app installed; referenced packages and input data must be available."),
    shiny::verbatimTextOutput(ns("code_display"), placeholder = TRUE),
    full_screen = TRUE
  )
}

#' Server for the code generation panel
#'
#' @param id    Module id
#' @param store reactiveValues store
code_panel_server <- function(id, store) {
  moduleServer(id, function(input, output, session) {
    ns <- session$ns

    r_script <- reactive({
      # Establish reactive deps so the panel re-renders whenever any task changes.
      # build_full_r_script uses isolate() internally, so we must touch them here.
      store$tasks
      store$task_order
      store$settings
      store$option_overrides
      .ig_options_state$revision()
      build_full_r_script(store)
    })

    parts <- reactive(code_pipeline_files(r_script()))
    selected_code <- reactive(parts()[[input$view %||% "pipeline"]])
    output$code_display <- renderText({ selected_code() })

    # Clipboard copy (uses JS writeText)
    shiny::observeEvent(input$copy_r, {
      session$sendCustomMessage("ig_copy_text", selected_code())
    })

    output$dl_r <- shiny::downloadHandler(
      filename = function() {
        paste0("pipeline_", format(Sys.Date(), "%Y%m%d"), ".R")
      },
      content = function(file) writeLines(r_script(), file)
    )
    output$dl_bundle <- shiny::downloadHandler(
      filename = function() paste0("pipeline_", format(Sys.Date(), "%Y%m%d"), ".zip"),
      content = function(file) ig_write_code_bundle(r_script(), file)
    )
  })
}
