main <- function() {
  Sys.setlocale("LC_CTYPE", ".UTF-8")
  Sys.setenv(CHROMOTE_CHROME = "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    NOT_CRAN = "true", LC_ALL = "English_Canada.utf8", LANG = "English_Canada.utf8")
  options(chromote.timeout = 180)
  browser <- chromote::Chromote$new(browser = chromote::Chrome$new(args = c(
    chromote::default_chrome_args(), "--no-first-run", "--no-default-browser-check",
    "--disable-sync", "--disable-background-networking")))
  chromote::set_default_chromote_object(browser)
  browser$default_timeout <- 180
  root <- normalizePath(".", winslash = "/")
  artifacts <- file.path(root, "artifacts", "audit", paste0("workflow-", format(Sys.time(), "%Y%m%d-%H%M%S")))
  dir.create(artifacts, recursive = TRUE)
  fixtures <- file.path(artifacts, "files"); dir.create(fixtures)
  write.csv(data.frame(x = 1:12, y = c(2, 5, 3, 8, 6, 9, 4, 10, 7, 13, 11, 14),
    group = rep(c("a", "b"), 6)), file.path(fixtures, "input.csv"), row.names = FALSE)
  sandbox <- tempfile("ig-workflow-"); dir.create(sandbox)
  writeLines(c("Sys.setlocale('LC_CTYPE', '.UTF-8')",
    sprintf("pkgload::load_all(%s, export_all = FALSE, helpers = FALSE, attach_testthat = FALSE)", deparse(root)),
    sprintf("options(ig.file_roots = c(Audit = %s), ig.catalogue_dir = file.path(tempdir(), 'workflow-catalogue'), ig.recovery_dir = file.path(tempdir(), 'workflow-recovery'))", deparse(fixtures)),
    "IndividualGuide::run_app()"), file.path(sandbox, "app.R"))
  app <- shinytest2::AppDriver$new(app_dir = sandbox, name = "workflow", width = 1440, height = 900,
    load_timeout = 180000, timeout = 120000, check_names = FALSE)
  on.exit({
  try({
    capture.output(dput(app$get_js("({busy:document.documentElement.className, panels:Array.from(document.querySelectorAll('.ig-task-panel')).map(e=>({id:e.id,token:e.dataset.igReadyToken,recalculating:Array.from(e.querySelectorAll('.recalculating')).map(x=>({id:x.id,visible:x.getClientRects().length>0}))})),ready:Object.entries(Shiny.shinyapp.$inputValues).filter(([k])=>k.endsWith('-ig_ready'))})")),
      file = file.path(artifacts, "readiness-state.R"))
    capture.output(print(app$get_logs()), file = file.path(artifacts, "browser-runtime.log"))
    app$get_screenshot(file = file.path(artifacts, "last-screen.png"))
    app$stop()
    }, silent = TRUE)
  try(app$stop(), silent = TRUE)
}, add = TRUE)
  cat("Artifacts:", artifacts, "\n")
  app$wait_for_js("!window.igDesktop && !document.documentElement.classList.contains('ig-desktop') && document.getElementById('btn_save').getClientRects().length > 0 && document.getElementById('btn_open').getClientRects().length > 0")
  cat("Normal browser keeps its Shiny Save/Open controls visible.\n")
  quote_js <- function(value) as.character(jsonlite::toJSON(value, auto_unbox = TRUE))
  click <- function(id) {
    app$wait_for_js(sprintf("(() => { const e = document.getElementById(%s); return e && !e.disabled && e.classList.contains('shiny-bound-input'); })()", quote_js(id)))
    app$run_js(sprintf("document.getElementById(%s).click()", quote_js(id)))
    app$wait_for_idle()
  }
  ready <- function(task_id) {
    suffix <- paste0("_", task_id, "-ig_ready")
    app$wait_for_js(sprintf("Object.entries(Shiny.shinyapp.$inputValues).some(([k,v]) => k.endsWith(%s) && typeof v === 'string' && v === document.getElementById(%s)?.dataset.igReadyToken)",
      quote_js(suffix), quote_js(paste0("panel_", task_id))))
    app$wait_for_idle()
  }
  wait_success <- function(task_id) {
    selector <- paste0("#panel_status_", task_id)
    app$wait_for_js(sprintf("document.querySelector(%s) !== null", quote_js(paste0(selector, " .ig-status-error, ", selector, " .ig-status-success"))))
    error <- app$get_js(sprintf("document.querySelector(%s)?.title || ''", quote_js(paste0(selector, " .ig-status-error"))))
    if (nzchar(error)) stop("Task ", task_id, " failed: ", error)
  }
  add_task <- function(type, number = 1L) {
    click("btn_add_task")
    app$wait_for_js("document.querySelector('#shiny-modal.show') !== null")
    app$run_js(sprintf("document.querySelector('[onclick*=\"picker_select\"][onclick*=%s]').click()", quote_js(type)))
    id <- paste0(gsub("_", "", type), "_", number)
    ready(id)
    app$expect_unique_names()
    id
  }
  app$wait_for_js("document.querySelector('#splash_fresh.shiny-bound-input') !== null")
  click("splash_fresh")
  app$wait_for_js("document.querySelector('.modal-backdrop') === null")
  id <- add_task("import_data")
  cat("Import panel ready.\n")
  if ("--ready-only" %in% commandArgs(trailingOnly = TRUE)) return(invisible(NULL))
  click(paste0("import_", id, "-file_picker"))
  app$wait_for_idle()
  app$wait_for_js("document.querySelector('.sF-file .sF-file-name') !== null")
  cat("File picker ready.\n")
  app$run_js("document.querySelector('.sF-file').click()")
  app$wait_for_js("!document.querySelector('.sF-modalContainer #sF-selectButton').disabled")
  cat("File selected.\n")
  app$run_js("document.querySelector('.sF-modalContainer #sF-selectButton').click()")
  app$wait_for_js("(() => { const m = document.querySelector('.sF-modalContainer'); return !m || getComputedStyle(m).display === 'none'; })()")
  cat("File picker closed.\n")
  app$get_screenshot(file = file.path(artifacts, "import-setup.png"))
  cat("Output name:", app$get_js("document.getElementById('import_importdata_1-output_name').value"), "\n")
  app$wait_for_js("document.getElementById('import_importdata_1-output_name').value === 'input'")
  app$set_inputs(`import_importdata_1-output_name` = "raw ' data")
  click("import_importdata_1-btn_refresh")
  wait_success("importdata_1")
  app$wait_for_idle()
  app$get_screenshot(file = file.path(artifacts, "import-result.png"))
  cat("Real CSV import succeeded with a quoted output name.\n")
  add_task("first_last_n")
  app$set_inputs(`fl_firstlastn_1-input_table` = "raw ' data", `fl_firstlastn_1-output_name` = "top_rows",
    `fl_firstlastn_1-n` = 3)
  click("btn_save")
  app$wait_for_idle()
  app$wait_for_js("document.querySelector('#sf_save_as-modal') !== null")
  app$get_screenshot(file = file.path(artifacts, "save-picker.png"))
  app$run_js("const name = document.querySelector('#sf_save_as-modal .sF-filename'); name.value = 'workflow'; name.dispatchEvent(new Event('input', {bubbles:true})); name.dispatchEvent(new Event('change', {bubbles:true}));")
  app$run_js("document.querySelector('#sf_save_as-modal #sF-selectButton').click()")
  app$wait_for_js("(() => { const m = document.querySelector('#sf_save_as-modal'); return !m || getComputedStyle(m).display === 'none'; })()")
  app$wait_for_idle()
  project <- file.path(fixtures, "workflow.igpx")
  deadline <- Sys.time() + 30
  while (!file.exists(project)) {
    if (Sys.time() > deadline) stop("Save As did not create the project file.")
    Sys.sleep(0.1)
  }
  pkgload::load_all(root, quiet = TRUE)
  loaded <- make_store(); project_load(loaded, project)
  stopifnot(shiny::isolate(loaded$tasks$firstlastn_1$params$n) == 3,
    is.null(shiny::isolate(loaded$tasks$firstlastn_1$run_time)),
    "raw ' data" %in% names(shiny::isolate(loaded$tables)))
  cat("Save As preserved an unrun configuration and quoted source.\n")
  app$set_inputs(`fl_firstlastn_1-n` = 2)
  click("panel_run_btn_firstlastn_1")
  wait_success("firstlastn_1")
  app$wait_for_js("document.body.innerText.includes('Preview — 2 rows')")
  app$set_inputs(`fl_firstlastn_1-n` = 4)
  app$wait_for_js("document.querySelector('#panel_status_firstlastn_1 .ig-status-success') === null")
  app$wait_for_js("!document.body.innerText.includes('Preview — 2 rows')")
  click("btn_save")
  app$wait_for_idle()
  project_load(loaded, project)
  stopifnot(shiny::isolate(loaded$tasks$firstlastn_1$params$n) == 4)
  cat("Run, edit, preview invalidation and overwrite Save passed.\n")
  click("btn_open")
  app$wait_for_js("document.querySelector('#sf_open-modal .sF-file') !== null")
  app$run_js("Array.from(document.querySelectorAll('#sf_open-modal .sF-file')).find(e => e.querySelector('.sF-file-name').innerText === 'workflow.igpx').click()")
  app$run_js("document.querySelector('#sf_open-modal #sF-selectButton').click()")
  app$wait_for_js("(() => { const m = document.querySelector('#sf_open-modal'); return !m || getComputedStyle(m).display === 'none'; })()")
  app$wait_for_js("Boolean(document.getElementById('project_open_trust')?.classList.contains('shiny-bound-input'))")
  click("project_open_trust")
  app$wait_for_idle()
  app$run_js("document.querySelector('[onclick*=\"tree_task_click\"][onclick*=\"firstlastn_1\"]').click()")
  ready("firstlastn_1")
  app$wait_for_js("document.getElementById('fl_firstlastn_1-n').value === '4'")
  app$expect_unique_names()
  app$run_js("document.querySelector('[onclick*=\"tree_run_flow\"]').click()")
  app$wait_for_js("document.body.innerText.includes('Flow finished: 2 succeeded')")
  app$wait_for_js("document.body.innerText.includes('Preview — 4 rows')")
  app$wait_for_idle()
  app$get_screenshot(file = file.path(artifacts, "reopened-flow-results.png"))
  cat("Same-ID project reopen and full-flow rerun passed.\n")
  add_task("linear_regression")
  app$set_inputs(`p3_linearregression_1-input_table` = "raw ' data")
  app$wait_for_js("document.getElementById('p3_linearregression_1-response').selectize.options.y !== undefined")
  app$set_inputs(`p3_linearregression_1-response` = "y", `p3_linearregression_1-predictors` = "x")
  click("panel_run_btn_linearregression_1")
  wait_success("linearregression_1")
  app$wait_for_idle()
  errors <- app$get_js("Array.from(document.querySelectorAll('.shiny-output-error:not(.shiny-output-error-validation)')).filter(e => e.getClientRects().length).map(e => e.innerText)")
  if (length(unlist(errors))) stop("Model preview render errors: ", paste(unlist(errors), collapse = " | "))
  app$get_screenshot(file = file.path(artifacts, "model-results.png"))
  add_task("script")
  app$set_inputs(`scr_script_1-input_tables` = "top_rows",
    `scr_script_1-output_name` = "script_rows", `scr_script_1-output_defs` = "script_rows: table")
  app$run_js("ace.edit('scr_script_1-code').setValue(\"stop('audit intentional failure')\", -1)")
  click("panel_run_btn_script_1")
  app$wait_for_js("document.querySelector('#panel_status_script_1 .ig-status-error')?.title.includes('audit intentional failure')")
  app$run_js("ace.edit('scr_script_1-code').setValue('script_rows <- transform(top_rows, doubled = x * 2)', -1)")
  click("panel_run_btn_script_1")
  wait_success("script_1")
  cat("Model, script failure diagnostics and corrected rerun passed.\n")
  click("btn_settings")
  app$wait_for_js("document.getElementById('settings_apply') !== null")
  app$set_inputs(settings_theme_mode = "light", settings_confirm_delete = FALSE, settings_page_length = 25)
  click("settings_apply")
  app$wait_for_js("document.documentElement.getAttribute('data-ig-theme') === 'light'")
  app$run_js("document.querySelector('#panel_script_1 [onclick*=\"panel_delete_task\"]').click()")
  app$wait_for_js("document.getElementById('panel_script_1') === null")
  click("btn_undo")
  app$wait_for_js("document.getElementById('panel_script_1') !== null")
  ready("script_1")
  app$wait_for_js("ace.edit('scr_script_1-code').getValue().includes('doubled')")
  click("panel_run_btn_script_1")
  wait_success("script_1")
  app$expect_unique_names()
  cat("Settings, delete, undo, restored code and recreated header Run passed.\n")
  click("btn_comments")
  app$wait_for_js("document.querySelector('#comment_body.shiny-bound-input') !== null && document.querySelector('#shiny-modal.show') !== null && getComputedStyle(document.querySelector('#shiny-modal')).opacity === '1'")
  app$wait_for_idle()
  app$set_inputs(comment_title = "Workflow audit", comment_body = "Quoted source and restored script verified")
  click("comment_add")
  app$wait_for_js("document.querySelector('#comments_threads_ui').innerText.includes('Quoted source and restored script verified')")
  app$wait_for_js("document.querySelector('input[id^=\"reply_\"].shiny-bound-input') !== null")
  reply <- app$get_js("document.querySelector('input[id^=\"reply_\"]').id")
  do.call(app$set_inputs, setNames(list("Verified reply"), reply))
  click(app$get_js("document.querySelector('button[id^=\"reply_btn_\"]').id"))
  app$wait_for_js("document.querySelector('#comments_threads_ui').innerText.includes('Verified reply')")
  click(app$get_js("document.querySelector('button[id^=\"resolve_btn_\"]').id"))
  app$wait_for_js("document.querySelector('#comments_threads_ui .ig-pill-resolved') !== null")
  click(app$get_js("document.querySelector('button[id^=\"resolve_btn_\"]').id"))
  app$wait_for_js("document.querySelector('#comments_threads_ui .ig-pill-open') !== null")
  app$set_inputs(comment_title = "Audit issue", comment_body = "")
  click("review_issue_add")
  close_modal <- function() {
    app$wait_for_idle()
    app$wait_for_js("(() => { const e = document.querySelector('#shiny-modal.show'); return e && getComputedStyle(e).opacity === '1' && !bootstrap.Modal.getInstance(e)?._isTransitioning; })()")
    app$run_js("document.querySelector('#shiny-modal [data-bs-dismiss=\"modal\"], #shiny-modal [data-dismiss=\"modal\"]').click()")
    app$wait_for_js("document.querySelector('.modal-backdrop') === null")
  }
  close_modal()
  click("btn_review")
  app$wait_for_js("document.querySelector('#review_dashboard_ui').innerText.includes('Audit issue')")
  click(app$get_js("document.querySelector('button[id^=\"resolve_issue_\"]').id"))
  app$wait_for_js("document.querySelector('#review_dashboard_ui').innerText.includes('No outstanding issues')")
  click("review_approve")
  app$wait_for_js("document.querySelector('#review_dashboard_ui').innerText.toLowerCase().includes('approved')")
  click("review_mode_toggle")
  close_modal()
  click("panel_run_btn_script_1")
  app$wait_for_js("document.body.innerText.toLowerCase().includes('review mode is read-only')")
  click("btn_review")
  app$wait_for_js("document.querySelector('#review_mode_toggle:checked') !== null")
  click("review_mode_toggle")
  close_modal()
  click("btn_search")
  app$wait_for_js("document.getElementById('global_search_query') !== null")
  app$set_inputs(global_search_query = "Quoted source")
  app$wait_for_js("document.querySelector('#shiny-modal').innerText.includes('Workflow audit')")
  close_modal()
  click("btn_history")
  app$wait_for_js("document.querySelector('#history_dt table') !== null")
  app$get_screenshot(file = file.path(artifacts, "history.png"))
  close_modal()
  cat("Comments, search and history rendered real changes.\n")
  click("btn_add_task")
  app$wait_for_js("document.querySelector('[onclick*=\"picker_fav_toggle\"][onclick*=\"first_last_n\"]') !== null")
  app$run_js("document.querySelector('[onclick*=\"picker_fav_toggle\"][onclick*=\"first_last_n\"]').click()")
  app$wait_for_js("document.querySelector('.ig-picker-star--on[onclick*=\"first_last_n\"]') !== null")
  close_modal()
  cat("Favourite toggle and picker Cancel passed.\n")
  click("btn_help")
  app$wait_for_js("document.getElementById('help_task_search') !== null")
  close_modal()
  click("btn_shortcuts")
  app$wait_for_js("document.querySelector('#shiny-modal').innerText.toLowerCase().includes('ctrl')")
  close_modal()
  cat("Help and shortcut guide opened and closed.\n")
  app$run_js("document.dispatchEvent(new KeyboardEvent('keydown', {key:'f', ctrlKey:true, altKey:true, bubbles:true}))")
  app$wait_for_idle()
  for (width in c(1440, 1280, 1024)) {
    app$set_window_size(width = width, height = 900)
    app$wait_for_idle()
    overflow <- app$get_js("document.documentElement.scrollWidth > window.innerWidth + 2")
    if (isTRUE(overflow)) stop("Page horizontal overflow at width ", width)
    app$get_screenshot(file = file.path(artifacts, paste0("workspace-light-", width, ".png")))
  }
  click("btn_save")
  app$wait_for_idle()
  project_load(loaded, project)
  stopifnot(shiny::isolate(loaded$settings$page_length) == 25,
    length(shiny::isolate(loaded$collaboration$comments)) == 1,
    identical(shiny::isolate(loaded$tasks$script_1$status), "success"),
    identical(shiny::isolate(loaded$tasks$linearregression_1$status), "success"),
    identical(shiny::isolate(loaded$tasks$linearregression_1$params$predictors), "x"),
    identical(shiny::isolate(loaded$tasks$script_1$params$input_tables), "top_rows"),
    identical(shiny::isolate(loaded$collaboration$review$status), "approved"),
    "first_last_n" %in% shiny::isolate(loaded$task_favourites))
  cat("Three desktop widths, keyboard shortcut and saved settings/comments/results passed.\n")
  app$run_js("document.querySelector('[onclick*=\"tree_copy_flow\"]').click()")
  app$wait_for_js("document.querySelectorAll('[onclick*=\"tree_copy_flow\"]').length === 2")
  app$wait_for_idle()
  app$run_js("document.querySelector('.ig-tree-flow-active [onclick*=\"tree_run_flow\"]').click()")
  app$wait_for_js("document.body.innerText.includes('Flow finished: 4 succeeded')")
  click("btn_save"); app$wait_for_idle()
  project_load(loaded, project)
  copied <- shiny::isolate(loaded$tasks)
  stopifnot(length(shiny::isolate(loaded$flows)) == 2L, length(copied) == 4L,
    all(vapply(copied, function(task) identical(task$status, "success"), logical(1))),
    "top_rows" %in% names(shiny::isolate(loaded$tables)))
  cat("Copied flow reran independently and preserved original results.\n")
  log <- capture.output(print(app$get_logs()))
  if (any(grepl("JS error|JS warning", log))) stop("Browser JavaScript diagnostics were recorded.")
}
main()
