main <- function() {
  Sys.setlocale("LC_CTYPE", ".UTF-8")
  Sys.setenv(CHROMOTE_CHROME = "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", NOT_CRAN = "true")
  options(chromote.timeout = 180)
  browser <- chromote::Chromote$new(browser = chromote::Chrome$new(args = c(
    chromote::default_chrome_args(), "--no-first-run", "--no-default-browser-check",
    "--disable-sync", "--disable-background-networking")))
  chromote::set_default_chromote_object(browser)
  browser$default_timeout <- 180
  pkgload::load_all(quiet = TRUE)
  root <- normalizePath(".", winslash = "/")
  artifacts <- file.path(root, "artifacts/audit", paste0("logging-", format(Sys.time(), "%Y%m%d-%H%M%S")))
  dir.create(artifacts, recursive = TRUE)
  files <- file.path(artifacts, "files"); dir.create(files)
  store <- make_store(); flow <- make_flow("Logging browser check")
  store$flows <- setNames(list(flow), flow$id); store$active_flow <- flow$id
  p <- default_script_params("answer")
  p$code <- "cat('console evidence\\n'); log_event('browser checkpoint'); warning('browser warning'); answer <- data.frame(x = 1:3)"
  p$output_defs <- list(list(name = "answer", kind = "table"))
  shiny::isolate(store_set_task(store, task_def("script_1", "script", output = "answer", params = p)))
  project <- file.path(files, "logging.igpx"); project_save(store, project)
  sandbox <- tempfile("ig-log-browser-"); dir.create(sandbox)
  writeLines(c("Sys.setlocale('LC_CTYPE', '.UTF-8')",
    sprintf("pkgload::load_all(%s, export_all = FALSE, helpers = FALSE, attach_testthat = FALSE)", deparse(root)),
    sprintf("options(ig.file_roots = c(Audit = %s), ig.recovery_dir = file.path(tempdir(), 'log-recovery'))", deparse(files)),
    "IndividualGuide::run_app()"), file.path(sandbox, "app.R"))
  app <- shinytest2::AppDriver$new(app_dir = sandbox, width = 1440, height = 1000,
    timeout = 60000, load_timeout = 120000, check_names = FALSE)
  on.exit({
    try(capture.output(print(app$get_logs()), file = file.path(artifacts, "runtime.log")), silent = TRUE)
    try(app$get_screenshot(file = file.path(artifacts, "last-screen.png")), silent = TRUE)
    try(app$stop(), silent = TRUE)
  }, add = TRUE)
  cat("Artifacts:", artifacts, "\n")
  q <- function(x) as.character(jsonlite::toJSON(x, auto_unbox = TRUE))
  click <- function(id) {
    app$wait_for_js(sprintf("document.getElementById(%s)?.classList.contains('shiny-bound-input')", q(id)))
    app$run_js(sprintf("document.getElementById(%s).click()", q(id))); app$wait_for_idle()
  }
  ready <- function(id) app$wait_for_js(sprintf("(() => {const p=document.getElementById(%s);return p?.dataset.igReadyToken && Object.entries(Shiny.shinyapp.$inputValues).some(([k,v])=>k.endsWith(%s)&&v===p.dataset.igReadyToken);})()", q(paste0("panel_", id)), q(paste0("_", id, "-ig_ready"))))
  open_project <- function() {
    click("btn_open")
    app$wait_for_js("document.querySelector('#sf_open-modal .sF-file') !== null")
    app$run_js("Array.from(document.querySelectorAll('#sf_open-modal .sF-file')).find(e=>e.querySelector('.sF-file-name').innerText==='logging.igpx').click()")
    app$wait_for_js("!document.querySelector('#sf_open-modal #sF-selectButton').disabled")
    app$run_js("document.querySelector('#sf_open-modal #sF-selectButton').click()")
    app$wait_for_js("(() => {const m=document.querySelector('#sf_open-modal');return !m || getComputedStyle(m).display==='none';})()")
    app$wait_for_idle()
  }
  click("splash_fresh"); app$wait_for_js("document.querySelector('.modal-backdrop') === null")
  open_project()
  app$run_js("document.querySelector('[onclick*=\"tree_task_click\"][onclick*=\"script_1\"]').click()")
  ready("script_1")
  app$run_js("document.querySelector('#panel_script_1 details > summary').click()")
  app$set_inputs(`log_script_1-min_level` = "DEBUG", `log_script_1-start_template` = "Browser start {task}")
  app$run_js("window.savedLogInput=document.getElementById('log_script_1-success_template');savedLogInput.focus();savedLogInput.select()")
  app$get_chromote_session()$Input$insertText(text = "Browser finish {status}; rows ")
  app$wait_for_idle()
  stopifnot(isTRUE(app$get_js("savedLogInput===document.getElementById('log_script_1-success_template') && document.activeElement===savedLogInput")))
  app$set_inputs(`log_script_1-field` = "{rows_out}")
  app$run_js("document.querySelector('#log_script_1-row_success [aria-label=\"Insert selected field\"]').click()")
  app$wait_for_js("savedLogInput.value==='Browser finish {status}; rows {rows_out}'")
  click("log_script_1-add_rule")
  app$wait_for_js("document.getElementById('log_script_1-rule_1_template')?.classList.contains('shiny-bound-input')")
  app$set_inputs(`log_script_1-rule_1_event` = "warning", `log_script_1-rule_1_level` = "ERROR",
    `log_script_1-rule_1_template` = "Audited {task}: {message}", `log_script_1-preview_event` = "warning")
  app$wait_for_js("document.getElementById('log_script_1-preview').innerText.includes('[ERROR] Audited script_1: Example warning')")
  click("log_script_1-add_rule")
  app$wait_for_js("document.getElementById('log_script_1-row_rule_2') !== null")
  app$run_js("document.querySelector('#log_script_1-row_rule_2 [aria-label=\"Remove this log rule\"]').click()")
  app$wait_for_js("document.getElementById('log_script_1-row_rule_2') === null")
  stopifnot(isTRUE(app$get_js("savedLogInput===document.getElementById('log_script_1-success_template')")))
  click("panel_run_btn_script_1")
  app$wait_for_js("document.querySelector('#panel_status_script_1 .ig-status-success') !== null")
  app$wait_for_js("document.getElementById('log_script_1-events').innerText.includes('browser checkpoint')")
  stopifnot(isTRUE(app$get_js("document.getElementById('log_script_1-events').innerText.includes('console evidence')")))
  app$set_inputs(`log_script_1-preview_event` = "success")
  app$wait_for_js("document.getElementById('log_script_1-preview').innerText.includes('Browser finish success; rows 3')")
  app$wait_for_js("document.getElementById('log_script_1-preview_inputs').innerText.includes('{rows_out}')")
  app$set_inputs(`log_script_1-preview_source` = "example", `log_script_1-preview_rows_in` = 95,
    `log_script_1-preview_rows_out` = 12, `log_script_1-preview_format` = "json")
  app$wait_for_js("document.getElementById('log_script_1-preview_entries').innerText.includes('Browser finish success; rows 12')")
  stopifnot(app$get_js("JSON.parse(document.getElementById('log_script_1-preview_file').innerText)[0].message") == "Browser finish success; rows 12")
  app$run_js("document.querySelector('#panel_script_1 .ig-log-preview-grid').scrollIntoView({block:'start'})")
  stopifnot(isTRUE(app$get_js("(() => {const e=document.querySelector('#panel_script_1 .ig-log-inputs-scroll');return e.clientHeight<500&&e.scrollHeight>e.clientHeight;})()")))
  app$get_screenshot(file = file.path(artifacts, "logging-visual-preview.png"))
  app$set_inputs(`log_script_1-preview_source` = "current", `log_script_1-preview_format` = "txt")
  app$wait_for_js("document.getElementById('log_script_1-preview_entries').innerText.includes('Browser finish success; rows 3')")
  cat("Rule add/remove and field insertion retain existing inputs; live preview and severity override work.\n")
  click("btn_add_task")
  app$wait_for_js("document.querySelector('#shiny-modal.show') !== null")
  app$run_js("document.querySelector('[onclick*=\"picker_select\"][onclick*=\"export_log\"]').click()")
  ready("exportlog_1")
  destination <- file.path(files, "pipeline.csv")
  app$set_inputs(`elog_exportlog_1-path` = destination, `elog_exportlog_1-format` = "csv", `elog_exportlog_1-overwrite` = TRUE)
  click("elog_exportlog_1-run")
  app$wait_for_js("document.querySelector('#panel_status_exportlog_1 .ig-status-success') !== null")
  data <- utils::read.csv(destination)
  stopifnot(all(c("browser checkpoint", "Browser start script_1", "Browser finish success; rows 3", "Audited script_1: browser warning") %in% data$message),
    data$level[data$message == "Audited script_1: browser warning"] == "ERROR")
  app$wait_for_js("document.getElementById('elog_exportlog_1-preview_file').innerText.includes('browser checkpoint')")
  stopifnot(identical(app$get_js("document.getElementById('elog_exportlog_1-preview_file').innerText"),
    paste(readLines(destination, encoding = "UTF-8", warn = FALSE), collapse = "\n")))
  app$set_inputs(`elog_exportlog_1-example_preview` = TRUE, `elog_exportlog_1-min_level` = "WARN", `elog_exportlog_1-format` = "json")
  app$wait_for_js("document.getElementById('elog_exportlog_1-preview_file').innerText.includes('Example warning')")
  stopifnot(app$get_js("JSON.parse(document.getElementById('elog_exportlog_1-preview_file').innerText).length") == 1L)
  app$set_inputs(`elog_exportlog_1-example_preview` = FALSE, `elog_exportlog_1-min_level` = "DEBUG", `elog_exportlog_1-format` = "csv")
  cat("Visual field inputs, example/current messages and exact CSV/JSON output previews pass without running tasks.\n")
  app$run_js("document.querySelector('#panel_exportlog_1 details > summary').click()")
  app$set_inputs(`log_exportlog_1-success_template` = "Custom export message")
  click("log_exportlog_1-reset_rules")
  app$wait_for_js("Array.from(document.querySelectorAll('#log_exportlog_1-rules input[type=text]')).some(e=>e.value.includes('wrote retained logs to {destination}'))")
  app$expect_unique_names()
  cat("Picker-created Export Log writes the selected task log to CSV.\n")
  app$run_js("document.querySelector('.ig-tree-flow-active [onclick*=\"tree_run_flow\"]').click()")
  app$wait_for_js("document.body.innerText.includes('Flow finished: 2 succeeded')")
  click("btn_save")
  loaded <- make_store(); project_load(loaded, project)
  stopifnot(shiny::isolate(loaded$tasks$script_1$logging$rules[[1L]]$template) == "Browser start {task}",
    nrow(shiny::isolate(ig_log_records(loaded$tasks, "script_1"))) >= 8L,
    shiny::isolate(loaded$tasks$exportlog_1$params$path) == destination)
  open_project()
  app$run_js("document.querySelector('[onclick*=\"tree_task_click\"][onclick*=\"script_1\"]').click()")
  ready("script_1")
  app$wait_for_js("document.getElementById('log_script_1-start_template').value==='Browser start {task}'")
  app$wait_for_js("document.getElementById('log_script_1-rule_1_level').value==='ERROR'")
  app$run_js("document.querySelector('#panel_script_1 details > summary').click()")
  app$set_inputs(`log_script_1-min_level` = "ERROR", `log_script_1-preview_event` = "success")
  app$wait_for_js("document.getElementById('log_script_1-preview').innerText.includes('No enabled rule')")
  app$set_inputs(`log_script_1-preview_event` = "warning", `log_script_1-rule_1_enabled` = FALSE)
  app$wait_for_js("document.getElementById('log_script_1-preview').innerText.includes('No enabled rule')")
  app$set_inputs(`log_script_1-rule_1_enabled` = TRUE)
  app$wait_for_js("document.getElementById('log_script_1-preview').innerText.includes('[ERROR] Audited script_1')")
  app$set_inputs(`log_script_1-min_level` = "DEBUG", `log_script_1-preview_event` = "success")
  app$run_js("document.getElementById('log_script_1-rules').scrollTop=0;document.querySelector('#panel_script_1 details').scrollIntoView({block:'start'});")
  app$get_screenshot(file = file.path(artifacts, "logging-builder.png"))
  app$run_js("document.getElementById('tabpill_code').click()")
  app$wait_for_js("document.getElementById('code-code_display').innerText.includes('# Pipeline ----')")
  pipeline_view <- app$get_js("document.getElementById('code-code_display').innerText")
  stopifnot(grepl("pipeline_support.R", pipeline_view, fixed = TRUE),
    !grepl("ig_capture_task_log <-", pipeline_view, fixed = TRUE))
  app$get_screenshot(file = file.path(artifacts, "readable-pipeline.png"))
  app$run_js("Shiny.addCustomMessageHandler('ig_copy_text', text => window.copiedCode = text)")
  click("code-copy_r")
  app$wait_for_js("window.copiedCode === document.getElementById('code-code_display').innerText")
  app$set_inputs(`code-view` = "support")
  app$wait_for_js("document.getElementById('code-code_display').innerText.includes('ig_capture_task_log <-')")
  app$set_inputs(`code-view` = "complete")
  app$wait_for_js("document.getElementById('code-code_display').innerText.includes('# Pipeline ----') && document.getElementById('code-code_display').innerText.includes('ig_capture_task_log <-')")
  complete_view <- app$get_js("document.getElementById('code-code_display').innerText")
  single <- file.path(files, "downloaded.R")
  archive <- file.path(files, "downloaded.zip")
  app$get_download("code-dl_r", filename = single)
  app$get_download("code-dl_bundle", filename = archive)
  writeLines(complete_view, file.path(artifacts, "complete-view.R"), useBytes = TRUE)
  same_code <- function(file, view) identical(sub("\n+$", "", paste(readLines(file, encoding = "UTF-8", warn = FALSE), collapse = "\n")), sub("\n+$", "", view))
  stopifnot(same_code(single, complete_view))
  bundle <- file.path(files, "Downloaded bundle Ω"); dir.create(bundle)
  zip::unzip(archive, exdir = bundle)
  stopifnot(same_code(file.path(bundle, "pipeline.R"), pipeline_view))
  for (file in c(single, file.path(bundle, "pipeline.R"))) {
    wrapper <- file.path(files, "verify-download.R")
    writeLines(c(paste0("source(", code_literal(file), ")"),
      "stopifnot(!'IndividualGuide' %in% loadedNamespaces(), nrow(answer) == 3L)",
      "stopifnot(all(vapply(.task_status, identical, logical(1), 'success')))"), wrapper, useBytes = TRUE)
    result <- system2(file.path(R.home("bin"), "Rscript.exe"), c("--vanilla", shQuote(wrapper)), stdout = TRUE, stderr = TRUE)
    stopifnot(is.null(attr(result, "status")))
  }
  cat("Code views, Copy R, real R/ZIP downloads and fresh-process execution pass.\n")
  app$expect_unique_names()
  errors <- app$get_js("Array.from(document.querySelectorAll('.shiny-output-error:not(.shiny-output-error-validation)')).filter(e=>e.getClientRects().length).map(e=>e.innerText)")
  stopifnot(!length(unlist(errors)))
  cat("Whole-flow rerun and Save/Open preserve logging controls, entries, and export configuration.\n")
}
main()
