'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { Menu } = require('electron');
module.exports = async ({ window, pause, state }) => {
  const checks = {}, js = source => window.webContents.executeJavaScript('{' + source + '\n}', true);
  async function wait(test, label) {
    const deadline = Date.now() + 60000;
    while (Date.now() < deadline) { if (await test()) return; await pause(75); }
    fs.writeFileSync(path.join(state,'console-failure.txt'),await js("document.body.innerText+'\\nRUN STATE '+JSON.stringify(window.igRunState)"));
    fs.writeFileSync(path.join(state,'console-failure.png'),(await window.webContents.capturePage()).toPNG());
    throw new Error('Console test timed out: ' + label);
  }
  const menu = id => Menu.getApplicationMenu().getMenuItemById(id);
  const log = () => js("document.getElementById('r_console-transcript').textContent");
  const idle = () => wait(() => js("document.querySelector('.ig-console')?.dataset.busy === 'false' && !document.getElementById('r_console-run').disabled"), 'console idle');
  const click = id => js(`document.getElementById(${JSON.stringify(id)}).click()`);
  const run = async code => {
    await idle();
    await js(`document.getElementById('r_console-editor').value=${JSON.stringify(code)}; document.getElementById('r_console-run').click()`);
    await wait(() => log().then(text => text.includes('> ' + code.split('\n')[0])), 'command received');
    await idle();
  };
  await wait(() => menu('open').enabled && js("Boolean(document.getElementById('splash_fresh')?.classList.contains('shiny-bound-input'))"), 'startup');
  await click('splash_fresh'); await wait(() => menu('add-task').enabled, 'fresh workspace');
  menu('add-task').click();
  await wait(() => js("Boolean(document.querySelector('[onclick*=\"picker_select\"][onclick*=\"script\"]'))"), 'script picker');
  await js("document.querySelector('[onclick*=\"picker_select\"][onclick*=\"script\"]').click()");
  await wait(() => js("Boolean(document.getElementById('panel_script_1')?.dataset.igReadyToken)"), 'script ready');
  await js("ace.edit('scr_script_1-code').setValue('console_data <- data.frame(value=c(2,4,6))',-1); document.getElementById('scr_script_1-output_name').value='console_data'; document.getElementById('scr_script_1-output_name').dispatchEvent(new Event('change',{bubbles:true})); document.getElementById('scr_script_1-output_defs').value='console_data: table'; document.getElementById('scr_script_1-output_defs').dispatchEvent(new Event('change',{bubbles:true}))");
  await wait(() => menu('run').enabled, 'flow run available'); menu('run').click();
  await wait(() => js("window.igRunState?.outcome==='finished'"), 'pipeline data');
  assert.ok(menu('console').enabled); menu('console').click();
  await wait(() => js("document.getElementById('panel_console').classList.contains('ig-panel-active')"), 'console tab');
  checks.nativeMenu = true;
  await run("answer <- sum(console_data$value)\ncat('SUM=',answer,' COPY=',sum(.project$tables$console_data$value),sep='')");
  assert.match(await log(), /SUM=12 COPY=12/); checks.projectData = true;
  await js("const e=document.getElementById('r_console-editor');e.value='console_data$va';e.setSelectionRange(e.value.length,e.value.length);e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new KeyboardEvent('keydown',{key:' ',code:'Space',ctrlKey:true,bubbles:true,cancelable:true}))");
  await wait(()=>js("!document.querySelector('.ig-console-completions').hidden && document.querySelector('.ig-console-completions [role=option]')?.textContent==='value'"),'column completion');
  await js("document.getElementById('r_console-editor').dispatchEvent(new KeyboardEvent('keydown',{key:'Tab',bubbles:true,cancelable:true}))");
  assert.equal(await js("document.getElementById('r_console-editor').value"),'console_data$value'); checks.columnCompletion=true;
  await js("const e=document.getElementById('r_console-editor');e.value='selected_value <- 123\\nstop(\"must not run\")';e.setSelectionRange(0,21);e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',ctrlKey:true,shiftKey:true,bubbles:true,cancelable:true}))");
  await wait(()=>log().then(t=>t.includes('> selected_value <- 123')),'selection received'); await idle();
  assert.equal(await js("document.getElementById('r_console-editor').value.includes('must not run')"),true);
  assert.equal((await log()).includes('Error: must not run'),false); checks.runSelectionKeepsDraft=true;
  assert.equal(await js("Boolean(document.querySelector('.ig-console-highlight .ig-r-string') && document.querySelector('.ig-console-highlight .ig-r-number'))"),true); checks.syntaxHighlighting=true;
  await js("document.querySelector('.ig-console-history-toggle').click();const e=document.querySelector('.ig-console-history-search');e.value='selected_value';e.dispatchEvent(new Event('input',{bubbles:true}))");
  assert.equal(await js("document.querySelectorAll('.ig-console-history-item').length"),1);
  await js("document.querySelector('.ig-console-history-item').click()");
  assert.equal(await js("document.getElementById('r_console-editor').value"),'selected_value <- 123'); checks.searchableHistory=true;
  await run("answer + 1\nmessage('console-message')\nwarning('console-warning')\nstop('console-error')");
  let text = await log();
  for (const pattern of [/\[1\] 13/, /console-message/, /Warning: console-warning/, /Error: console-error/]) assert.match(text, pattern);
  checks.persistentWorkspace = true; checks.conditions = true;
  assert.equal(await js("document.querySelectorAll('.ig-console-plot').length"), 0);
  await run("plot(console_data$value, main='Console plot')");
  await wait(() => js("Array.from(document.querySelectorAll('.ig-console-plot')).some(e=>e.complete && e.naturalWidth===1000)"), 'plot image');
  checks.plots = true;
  assert.equal(await js("document.querySelectorAll('.ig-console-plot').length"), 1);
  await run("cat('<img src=x onerror=alert(1)>')");
  assert.equal(await js("document.querySelector('#r_console-transcript img')===null && document.querySelectorAll('.ig-console-plot').length===1"), true); checks.safeOutput = true; checks.noBlankPlots = true;
  // Recall a real command, then return to the unsent draft.
  await js("const e=document.getElementById('r_console-editor'); e.value='draft text'; e.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowUp',altKey:true,bubbles:true}))");
  assert.equal(await js("document.getElementById('r_console-editor').value"), "cat('<img src=x onerror=alert(1)>')");
  await js("document.getElementById('r_console-editor').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',altKey:true,bubbles:true}))");
  assert.equal(await js("document.getElementById('r_console-editor').value"), 'draft text'); checks.historyAndDraft = true;
  await js("window.consoleEditorNode=document.getElementById('r_console-editor'); consoleEditorNode.value='Sys.sleep(60)'; consoleEditorNode.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',ctrlKey:true,bubbles:true}))");
  await wait(() => js("!document.getElementById('r_console-stop').disabled"), 'stop available');
  menu('flow').click();
  await wait(() => js("document.getElementById('panel_flow').classList.contains('ig-panel-active')"), 'responsive flow tab');
  menu('console').click();
  await js("consoleEditorNode.value='draft while running'"); await pause(400);
  assert.equal(await js("document.getElementById('r_console-editor')===consoleEditorNode && consoleEditorNode.value==='draft while running'"), true);
  checks.responsiveWhileRunning = true; checks.stableEditor = true; checks.ctrlEnter = true;
  await click('r_console-stop'); await idle(); assert.match(await log(), /Stopped\. Console workspace cleared/);
  assert.equal(await js("consoleEditorNode.value"), 'draft while running'); checks.stopPreservesDraft = true;
  await run("cat('OLD=',exists('answer'),sep='')"); assert.match(await log(), /OLD=FALSE/); checks.stopAndRestart = true;
  await run("private <- 41; console_data$value <- 0");
  await click('r_console-refresh'); await wait(() => log().then(t=>t.includes('[Refresh project data]')), 'refresh received'); await idle();
  await run("cat('REFRESH=',sum(console_data$value),' PRIVATE=',private,sep='')");
  assert.match(await log(), /REFRESH=12 PRIVATE=41/); checks.refreshKeepsUserVariables = true;
  const download = path.join(state, 'console-transcript.txt');
  const downloaded = new Promise(resolve => window.webContents.session.once('will-download', (_event, item) => {
    item.setSavePath(download); item.once('done', (_e, result) => resolve(result));
  }));
  await click('r_console-download');
  assert.equal(await Promise.race([downloaded, pause(30000).then(()=> 'timeout')]), 'completed');
  assert.match(fs.readFileSync(download,'utf8'), /REFRESH=12 PRIVATE=41/); checks.transcriptDownload = true;
  window.setSize(1024,768); await pause(200);
  assert.equal(await js("document.documentElement.scrollWidth <= window.innerWidth && document.querySelector('.ig-console-editor').getBoundingClientRect().bottom <= innerHeight"), true);
  checks.smallWindow = true;
  fs.writeFileSync(path.join(state,'console.png'), (await window.webContents.capturePage()).toPNG());
  await click('r_console-reset'); await wait(()=>log().then(t=>t.startsWith('R console reset.')), 'reset');
  await js("document.getElementById('r_console-editor').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowUp',altKey:true,bubbles:true}))");
  assert.equal(await js("document.getElementById('r_console-editor').value"), ''); checks.resetClearsHistory = true;
  await run("cat('RESET=',exists('private'),sep='')"); assert.match(await log(), /RESET=FALSE/);
  await js("(()=>{const e=document.getElementById('r_console-editor');e.value='6 * 7';e.focus()})()");
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Return' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Return' });
  await wait(() => log().then(t=>t.includes('> 6 * 7')), 'native Enter'); await idle();
  assert.match(await log(), /\[1\] 42/); checks.enterRuns = true;
  await js("(()=>{const e=document.getElementById('r_console-editor');e.value='draft';e.setSelectionRange(5,5)})()");
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Up' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Up' }); await pause(100);
  assert.equal(await js("document.getElementById('r_console-editor').value"), '6 * 7');
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Down' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Down' }); await pause(100);
  assert.equal(await js("document.getElementById('r_console-editor').value"), 'draft'); checks.arrowHistory = true;
  await js("document.getElementById('r_console-editor').value='Sys.sleep(60)'");
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Return' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Return' });
  await wait(()=>js("document.querySelector('.ig-console').dataset.busy==='true'"),'interrupt command');
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'C', modifiers: ['control'] });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'C', modifiers: ['control'] }); await idle();
  assert.match(await log(), /Stopped\. Console workspace cleared/); checks.nativeCtrlC = true;
  await run('reusable_result <- data.frame(total = sum(console_data$value))');
  await js("document.querySelector('.ig-console-create-script').click()");
  await wait(()=>js("Array.from(document.querySelectorAll('.ig-task-panel')).some(e=>e.id!=='panel_script_1' && e.dataset.igReadyToken && e.classList.contains('ig-panel-active') && e.querySelector('.ace_editor') && ace.edit(e.querySelector('.ace_editor').id).getValue().includes('reusable_result <-'))"),'create Script task');
  const code=await js("ace.edit(document.querySelector('.ig-task-panel.ig-panel-active .ace_editor').id).getValue()");
  assert.match(code,/reusable_result <-/); checks.createScriptTask=true;
  await js("document.querySelector('.ig-task-panel.ig-panel-active [id^=panel_run_btn_]').click()");
  await wait(()=>js("Boolean(document.querySelector('.ig-task-panel.ig-panel-active .ig-status-success'))"),'created Script run');
  return { ok: true, checks, transcript: download };
};
